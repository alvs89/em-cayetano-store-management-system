const normalizeSpaces = value => String(value || '').replace(/\s+/g, ' ').trim();

const parsePrice = rawPrice => {
  const text = String(rawPrice || '').trim();
  const number = Number(text.replace(/,/g, '').match(/\d+(?:\.\d+)?/)?.[0]);
  return Number.isFinite(number) ? number : null;
};

const buildEmCayetanoCatalog = () => {
  let currentCategory = null;
  const seen = new Set();
  const catalog = [];

  for (const rawLine of CATALOG_SOURCE.split(/\r?\n/)) {
    const line = normalizeSpaces(rawLine);
    if (!line) continue;

    const heading = line.toUpperCase();
    if (CATEGORY_HEADINGS.has(heading)) {
      currentCategory = CATEGORY_LABELS[heading];
      continue;
    }

    if (!currentCategory || !line.includes('--') || !/then\s+srp\s*:/i.test(line)) continue;

    const match = line.match(/^(.*?)\s+then\s+srp\s*:\s*(.+)$/i);
    if (!match) continue;

    const rawName = normalizeSpaces(match[1]);
    const priceText = normalizeSpaces(match[2]);
    const name = normalizeSpaces(priceText.toUpperCase().includes('/FT') ? `${rawName} (per ft)` : rawName).slice(0, 150);
    const price = parsePrice(priceText);
    const key = `${currentCategory}|${name.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);

    catalog.push({
      name,
      category: currentCategory,
      price,
      costPrice: price === null ? null : Number((price * 0.82).toFixed(2))
    });
  }

  return catalog;
};

